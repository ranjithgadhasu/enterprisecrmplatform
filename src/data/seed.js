function atMonth(offset, day, hour = 11) {
  const now = new Date();
  return new Date(now.getFullYear(), now.getMonth() - offset, day, hour, 0, 0).toISOString();
}

function ago(days, hour = 10) {
  const date = subDays(new Date(), days);
  date.setHours(hour, 15, 0, 0);
  return date.toISOString();
}

function ahead(days, hour = 15) {
  const date = addDays(new Date(), days);
  date.setHours(hour, 0, 0, 0);
  return date.toISOString();
}

function thisMonth(index) {
  const now = new Date();
  const day = Math.max(1, now.getDate() - (index + 1) * 2);
  return new Date(now.getFullYear(), now.getMonth(), day, 11, 0, 0).toISOString();
}

function slug(name) {
  return name.toLowerCase().replace(/[^a-z0-9]+/g, "");
}

